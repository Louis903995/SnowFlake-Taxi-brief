-- Installation de l'entrepôt : à exécuter une fois, avec ACCOUNTADMIN.
-- Rejouable : chaque instruction utilise IF NOT EXISTS.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS WH_TAXI
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS TAXI_DB;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.RAW;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS TAXI_DB.MARTS;

CREATE ROLE IF NOT EXISTS ROLE_TAXI_TOOLS;

GRANT USAGE, OPERATE ON WAREHOUSE WH_TAXI TO ROLE ROLE_TAXI_TOOLS;
GRANT USAGE ON DATABASE TAXI_DB TO ROLE ROLE_TAXI_TOOLS;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA TAXI_DB.RAW TO ROLE ROLE_TAXI_TOOLS;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA TAXI_DB.STAGING TO ROLE ROLE_TAXI_TOOLS;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA TAXI_DB.INTERMEDIATE TO ROLE ROLE_TAXI_TOOLS;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA TAXI_DB.MARTS TO ROLE ROLE_TAXI_TOOLS;

CREATE USER IF NOT EXISTS SVC_TAXI_PIPELINE
  TYPE = SERVICE
  DEFAULT_ROLE = ROLE_TAXI_TOOLS
  DEFAULT_WAREHOUSE = WH_TAXI;
GRANT ROLE ROLE_TAXI_TOOLS TO USER SVC_TAXI_PIPELINE;

